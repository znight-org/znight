/** Lifecycle state of an {@link Application}. */
export type ApplicationState = 'created' | 'starting' | 'ready' | 'stopping' | 'stopped' | 'failed'

/** Values keyed by token or class: a `Map`, an iterable of pairs, or a record keyed by token. */
export type ProviderValues = Iterable<readonly [ProviderKey, unknown]> | Readonly<Record<Token, unknown>>

/** Graceful shutdown settings. */
export interface ShutdownOptions {
  /** Signals stopping the application once started. Default: `['SIGINT', 'SIGTERM']`; `false` disables. */
  readonly signals?: readonly ShutdownSignal[] | false
  /**
   * Global deadline of `stop()`, in milliseconds. Default: 10 000. `Infinity` (or any value above
   * 2^31 - 1, the range of timers) means no deadline.
   */
  readonly timeoutMs?: number
  /**
   * Maximum duration of each shutdown step (hook or disposal), in milliseconds. Default: 5 000.
   * `Infinity` (or any value above 2^31 - 1) means no limit.
   */
  readonly hookTimeoutMs?: number
  /** Process used for signals, `exitCode` and forced exits. Default: the global `process`. */
  readonly process?: ProcessLike
}

/**
 * Hot module replacement handle (`import.meta.hot`). The dispose callback returns the `stop()`
 * promise, so that runtimes awaiting it (Vite's module runner, Bun) load the new module once the
 * application has stopped.
 */
export interface HotContext {
  dispose(callback: (data: unknown) => void | Promise<void>): void
}

/** Options of {@link Application.create}. */
export interface ApplicationOptions {
  /** The metadata generated by `@znight/compiler` (`__ZNIGHT_METADATA__`). */
  readonly metadata: ZnightMetadata
  readonly plugins?: readonly Plugin[]
  /** Values supplied by the application (externals, configuration...). Superseded by plugins. */
  readonly providers?: ProviderValues
  /** Replacements applied after plugins registered (highest precedence): values or provider definitions. */
  readonly overrides?: ProviderValues
  /** Initial logger. Default: a console logger (level `info`). Replace it later with `setLogger()`. */
  readonly logger?: CoreLogger
  readonly shutdown?: ShutdownOptions
  /** Forwarded to `container.init()` (e.g. `{ only: [UserController] }`). */
  readonly init?: InitOptions
  /** Pass `import.meta.hot` to stop the application when the module is replaced. */
  readonly hot?: HotContext
}

const DEFAULT_SIGNALS: readonly ShutdownSignal[] = ['SIGINT', 'SIGTERM']
const DEFAULT_TIMEOUT_MS = 10_000
const DEFAULT_HOOK_TIMEOUT_MS = 5_000
const FORCED_EXIT_CODE = 130

/**
 * Carries a marker through the async context of the start hook in progress, so that `stop()` can
 * tell a request coming from that hook (which must not wait for the start: the start waits for it).
 */
const startHookContext = new AsyncLocalStorage<object>()

/**
 * A Znight application: a container built from the compiled metadata, plugins and the lifecycle
 * tying them together.
 *
 * ```ts
 * const app = await Application.create({
 *   metadata: __ZNIGHT_METADATA__,
 *   plugins: [HttpPlugin.configure({ port: 3000 })],
 * })
 * await app.start()
 * ```
 */
export class Application {
  readonly container: Container
  readonly hooks: Hooks
  readonly metadata: ZnightMetadata
  readonly #logger: DelegatingLogger
  readonly #plugins: readonly Plugin[]
  readonly #pluginsByName: ReadonlyMap<string, Plugin>
  readonly #context: PluginContext
  readonly #signals: readonly ShutdownSignal[]
  readonly #process: ProcessLike | undefined
  readonly #timeoutMs: number
  readonly #hookTimeoutMs: number
  #state: ApplicationState = 'created'
  #startPromise: Promise<void> | undefined
  #stopPromise: Promise<void> | undefined
  /** Plugins whose `register` was attempted (they all receive `onDispose`). */
  readonly #registered: Plugin[] = []
  /** Plugins whose `onStart` completed (they receive `onStop`). */
  readonly #startedPlugins: Plugin[] = []
  /** Providers whose `onStart` completed (they receive `onStop`). */
  readonly #startedProviders = new Set<Token>()
  #listening: readonly ShutdownSignal[] = []
  #signalReceived = false
  /** Marker of the start hook in progress (see `startHookContext`). */
  #startHookMarker: object | undefined
  /** A start hook called `stop()`: the remaining start hooks are skipped. */
  #startAborted = false
  /** Releases a `stop()` waiting for the start, when a start hook asks to stop in turn. */
  #releaseStopWait: (() => void) | undefined

  private constructor(options: ApplicationOptions) {
    const plugins = [...(options.plugins ?? [])]
    const byName = new Map<string, Plugin>()
    for (const plugin of plugins) {
      if (plugin === null || typeof plugin !== 'object' || typeof plugin.name !== 'string' || plugin.name === '') {
        throw new ZnightError(ErrorCode.InvalidDecorator, `Invalid plugin: ${errorMessage(plugin)} has no name`)
      }
      if (byName.has(plugin.name)) {
        throw new ZnightError(ErrorCode.DuplicateProvider, `Duplicate plugin "${plugin.name}"`, {
          hints: ['Each plugin can be added once to Application.create({ plugins })'],
        })
      }
      byName.set(plugin.name, plugin)
    }
    this.#plugins = plugins
    this.#pluginsByName = byName
    this.metadata = options.metadata
    this.container = Container.create(options.metadata)
    this.#logger = new DelegatingLogger(options.logger ?? createConsoleLogger())
    this.hooks = new Hooks({ logger: this.#logger })

    const shutdown = options.shutdown ?? {}
    this.#process = shutdown.process ?? defaultProcess()
    this.#signals = shutdown.signals === false ? [] : [...(shutdown.signals ?? DEFAULT_SIGNALS)]
    this.#timeoutMs = positive(shutdown.timeoutMs, DEFAULT_TIMEOUT_MS, 'shutdown.timeoutMs')
    this.#hookTimeoutMs = positive(shutdown.hookTimeoutMs, DEFAULT_HOOK_TIMEOUT_MS, 'shutdown.hookTimeoutMs')

    bindBuiltin(this.container, CoreTokens.Application, this, Application)
    bindBuiltin(this.container, CoreTokens.Hooks, this.hooks, Hooks)
    bindBuiltin(this.container, CoreTokens.Logger, this.#logger)

    this.#context = Object.freeze({
      app: this,
      container: this.container,
      metadata: this.metadata,
      hooks: this.hooks,
      logger: this.#logger,
      getPlugin: <P extends Plugin = Plugin>(name: string): P | undefined => this.getPlugin<P>(name),
    })
  }

  /**
   * Creates the container, supplies `providers`, runs plugins' `register` (in order), applies
   * `overrides`, initialises the container and runs plugins' `onBootstrap`. On failure everything
   * created so far is disposed (plugins receive `onDispose`) and the error is rethrown.
   */
  static async create(options: ApplicationOptions): Promise<Application> {
    const app = new Application(options)
    await app.#bootstrap(options)
    return app
  }

  /** Current lifecycle state. */
  get state(): ApplicationState {
    return this.#state
  }

  /** The application logger (live: follows {@link setLogger}). */
  get logger(): CoreLogger {
    return this.#logger
  }

  /** Plugins, in registration order. */
  get plugins(): readonly Plugin[] {
    return this.#plugins
  }

  /** Replaces the logger used by the core and every plugin holding `ctx.logger`. */
  setLogger(logger: CoreLogger): void {
    this.#logger.setTarget(logger)
  }

  /** A plugin of the application, by name. */
  getPlugin<P extends Plugin = Plugin>(name: string): P | undefined {
    return this.#pluginsByName.get(name) as P | undefined
  }

  /** Shortcut for `app.container.get(key)`. */
  get<T>(key: ProviderClass<T>): T
  get<T>(key: ClassKey<T>): T
  get<T = unknown>(key: TypedToken<T>): T
  get(key: ProviderKey): unknown {
    return this.container.get(key as TypedToken<unknown>)
  }

  async #bootstrap(options: ApplicationOptions): Promise<void> {
    const container = this.container
    try {
      if (options.providers !== undefined) {
        for (const [key, value] of entriesOf(options.providers)) container.provide(key, value)
      }
      for (const plugin of this.#plugins) {
        this.#registered.push(plugin)
        setRegistrationOrigin(container, `plugin "${plugin.name}"`)
        try {
          await this.#callPlugin(plugin, 'register')
        } finally {
          setRegistrationOrigin(container, undefined)
        }
      }
      if (options.overrides !== undefined) {
        for (const [key, value] of entriesOf(options.overrides)) container.override(key, value)
      }
      await container.init(options.init)
      for (const plugin of this.#plugins) await this.#callPlugin(plugin, 'onBootstrap')
    } catch (error) {
      this.#state = 'failed'
      // nothing was started yet: this disposes the providers and runs plugins' onDispose
      addSuppressedErrors(error, await this.#shutdown())
      throw error
    }
    // the HMR runtime awaits the returned promise before it loads the new module
    options.hot?.dispose(() =>
      this.stop().catch((error: unknown) => this.#logger.error('Failed to stop the application', { err: error })),
    )
  }

  // ---------------------------------------------------------------------------------------------
  // start / stop
  // ---------------------------------------------------------------------------------------------

  /**
   * Starts the application: providers' `onStart` (resolution order) → plugins' `onStart` →
   * providers' `onReady` → plugins' `onReady`, then `state === 'ready'`. Signal handlers are
   * installed when the start begins. On failure, what was started is stopped, everything is
   * disposed, `state === 'failed'` and the error is rethrown (cleanup errors attached).
   * Calling it while starting returns the same promise; once ready it resolves immediately.
   * When a start hook calls `stop()` (e.g. a job that ends its work in `onReady`), the remaining
   * start hooks are skipped and the promise resolves once the application is stopped.
   */
  start(): Promise<void> {
    switch (this.#state) {
      case 'created':
        this.#startPromise = this.#runStart()
        return this.#startPromise
      case 'starting':
        return this.#startPromise as Promise<void>
      case 'ready':
        return Promise.resolve()
      default:
        return Promise.reject(
          new ZnightError(ErrorCode.LifecycleFailed, `Cannot start the application: it is ${this.#state}`),
        )
    }
  }

  async #runStart(): Promise<void> {
    this.#state = 'starting'
    this.#installSignals()
    let completed: boolean
    try {
      completed = await this.#runStartHooks()
    } catch (error) {
      if (this.#startAborted) {
        // the shutdown requested by a start hook owns the cleanup
        await this.#settledStop()
        throw error
      }
      addSuppressedErrors(error, await this.#shutdown())
      this.#removeSignals()
      this.#state = 'failed'
      throw error
    }
    if (!completed) {
      await this.#settledStop()
      return
    }
    this.#state = 'ready'
    this.#logger.debug('Application started')
  }

  /** Runs the start hooks in order; `false` when one of them called `stop()` (the others are skipped). */
  async #runStartHooks(): Promise<boolean> {
    const providers = this.container.instances()
    for (const provider of providers) {
      if (!(await this.#startHook(() => this.#callProvider(provider, 'onStart')))) return false
      this.#startedProviders.add(provider.token)
    }
    for (const plugin of this.#plugins) {
      if (!(await this.#startHook(() => this.#callPlugin(plugin, 'onStart')))) return false
      this.#startedPlugins.push(plugin)
    }
    for (const provider of providers) {
      if (!(await this.#startHook(() => this.#callProvider(provider, 'onReady')))) return false
    }
    for (const plugin of this.#plugins) {
      if (!(await this.#startHook(() => this.#callPlugin(plugin, 'onReady')))) return false
    }
    return true
  }

  /**
   * Runs one start hook in an async context carrying a fresh marker, so that a `stop()` called from
   * it (or from work it awaits) is recognised. Returns `false` when the hook stopped the application.
   */
  async #startHook(hook: () => Promise<void>): Promise<boolean> {
    const marker = {}
    this.#startHookMarker = marker
    try {
      await startHookContext.run(marker, hook)
    } finally {
      this.#startHookMarker = undefined
    }
    return !this.#startAborted
  }

  /** Whether the caller runs in the async context of the start hook in progress. */
  #calledFromStartHook(): boolean {
    const marker = this.#startHookMarker
    return this.#state === 'starting' && marker !== undefined && startHookContext.getStore() === marker
  }

  /** Waits for the stop requested by a start hook; its errors belong to the caller of `stop()`. */
  async #settledStop(): Promise<void> {
    try {
      await this.#stopPromise
    } catch {
      // reported by the stop() promise
    }
  }

  /**
   * Stops the application (idempotent; waits for an in-progress `start()`):
   * plugins' `onStop` (reverse) → providers' `onStop` + disposal (reverse resolution order) →
   * plugins' `onDispose` (reverse). Every step is attempted, each within `hookTimeoutMs` and all
   * within `timeoutMs`; failures are collected into a ZnightAggregateError (ZNIGHT021). Signal
   * handlers are removed.
   *
   * Called from a start hook (`onStart`/`onReady` of a provider or plugin, or work it awaits), it
   * does not wait for the start, which waits for that hook: the shutdown runs right away, stopping
   * what completed its `onStart`, and the remaining start hooks are skipped.
   */
  stop(): Promise<void> {
    if (this.#calledFromStartHook()) {
      this.#startAborted = true
      this.#releaseStopWait?.() // a stop() already waiting for the start must not wait for this hook
    }
    this.#stopPromise ??= this.#runStop()
    return this.#stopPromise
  }

  async #runStop(): Promise<void> {
    if (this.#state === 'starting' && !this.#startAborted) await this.#waitForStart()
    if (this.#state === 'failed' || this.#state === 'stopped') {
      this.#removeSignals()
      return
    }
    this.#state = 'stopping'
    const errors = await this.#shutdown()
    this.#removeSignals()
    this.#state = 'stopped'
    if (errors.length > 0) {
      throw new ZnightAggregateError(
        ErrorCode.LifecycleFailed,
        `The application stopped with ${errors.length} error(s)`,
        errors,
      )
    }
    // after a signal, the end of the shutdown is reported at the level of "Received SIGTERM"
    if (this.#signalReceived) this.#logger.info('Application stopped')
    else this.#logger.debug('Application stopped')
  }

  /**
   * Resolves when the start in progress settles (a failed start already stopped and disposed
   * everything), or earlier when a start hook asks to stop (see `stop()`).
   */
  async #waitForStart(): Promise<void> {
    await new Promise<void>(resolve => {
      this.#releaseStopWait = resolve
      const done = (): void => resolve()
      this.#startPromise?.then(done, done)
    })
    this.#releaseStopWait = undefined
  }

  /**
   * The three shutdown phases (also used to roll back a failed create/start: only what was started
   * is stopped). Never throws: returns the errors of the failed steps.
   */
  async #shutdown(): Promise<unknown[]> {
    const errors: unknown[] = []
    const step = this.#stepRunner(errors)
    for (const plugin of [...this.#startedPlugins].reverse()) {
      if (typeof plugin.onStop === 'function') {
        await step(`Plugin "${plugin.name}" onStop()`, () => plugin.onStop?.(this.#context))
      }
    }
    for (const provider of this.container.instances().reverse()) {
      if (this.#startedProviders.has(provider.token) && hasLifecycleHook(provider.instance, 'onStop')) {
        await step(`${provider.displayName}.onStop()`, () => callLifecycleHook(provider.instance, 'onStop'))
      }
      if (isDisposable(provider.instance, provider.definition.dispose)) {
        await step(`Disposing ${provider.displayName}`, () => provider.dispose())
      } else {
        await provider.dispose()
      }
    }
    try {
      await this.container.dispose()
    } catch (error) {
      errors.push(...flatten(error))
    }
    for (const plugin of [...this.#registered].reverse()) {
      if (typeof plugin.onDispose === 'function') {
        await step(`Plugin "${plugin.name}" onDispose()`, () => plugin.onDispose?.(this.#context))
      }
    }
    this.#startedPlugins.length = 0
    this.#startedProviders.clear()
    return errors
  }

  /** Runs labelled steps with a per-step timeout inside a global deadline, collecting failures. */
  #stepRunner(errors: unknown[]): (label: string, fn: () => unknown) => Promise<void> {
    const deadline = now() + this.#timeoutMs
    return async (label, fn) => {
      const budget = Math.max(0, Math.min(this.#hookTimeoutMs, deadline - now()))
      try {
        await runWithTimeout(label, fn, budget)
      } catch (error) {
        const failure = error instanceof StepTimeoutError ? error : shutdownError(label, error)
        errors.push(failure)
        this.#logger.debug(`${label} failed`, { err: error })
      }
    }
  }

  async #callPlugin(plugin: Plugin, hook: PluginHook): Promise<void> {
    const fn = plugin[hook]
    if (typeof fn !== 'function') return
    try {
      await fn.call(plugin, this.#context)
    } catch (error) {
      throw lifecycleError(`Plugin "${plugin.name}" ${hook}()`, error)
    }
  }

  async #callProvider(provider: ManagedInstance, hook: LifecycleHook): Promise<void> {
    if (!hasLifecycleHook(provider.instance, hook)) return
    try {
      await callLifecycleHook(provider.instance, hook)
    } catch (error) {
      throw lifecycleError(`${provider.displayName}.${hook}()`, error)
    }
  }

  // ---------------------------------------------------------------------------------------------
  // Signals
  // ---------------------------------------------------------------------------------------------

  #installSignals(): void {
    const proc = this.#process
    if (proc === undefined || this.#signals.length === 0 || this.#listening.length > 0) return
    for (const signal of this.#signals) proc.on(signal, this.#onSignal)
    this.#listening = this.#signals
  }

  #removeSignals(): void {
    const proc = this.#process
    if (proc === undefined) return
    for (const signal of this.#listening) proc.off(signal, this.#onSignal)
    this.#listening = []
  }

  readonly #onSignal = (signal: string): void => {
    const proc = this.#process
    if (proc === undefined) return
    if (this.#signalReceived) {
      this.#logger.warn(`Received ${signal} again: forcing exit`)
      proc.exit(FORCED_EXIT_CODE)
      return
    }
    this.#signalReceived = true
    this.#logger.info(`Received ${signal}: shutting down gracefully`)
    // success is logged by the stop itself ("Application stopped")
    this.stop().catch((error: unknown) => {
      this.#logger.error('The application stopped with errors', { err: error })
      proc.exitCode = 1
    })
  }
}

function entriesOf(values: ProviderValues): Iterable<readonly [ProviderKey, unknown]> {
  if (typeof (values as Partial<Iterable<unknown>>)[Symbol.iterator] === 'function') {
    return values as Iterable<readonly [ProviderKey, unknown]>
  }
  return Object.entries(values)
}

function flatten(error: unknown): unknown[] {
  return error instanceof ZnightAggregateError ? [...error.errors] : [error]
}

function shutdownError(step: string, error: unknown): ZnightError {
  return new ZnightError(ErrorCode.LifecycleFailed, `${step} failed: ${errorMessage(error)}`, { cause: error })
}

/** A duration in milliseconds: a non-negative number, `Infinity` meaning no limit. */
function positive(value: number | undefined, fallback: number, name: string): number {
  if (value === undefined) return fallback
  if (typeof value !== 'number' || Number.isNaN(value) || value < 0) {
    throw new ZnightError(
      ErrorCode.InvalidDecorator,
      `Invalid ${name}: expected a positive number of milliseconds (or Infinity), got ${value}`,
    )
  }
  return value
}
