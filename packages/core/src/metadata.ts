/**
 * Runtime metadata contract.
 *
 * `@znight/compiler` analyzes the application at build time and generates a module exporting a
 * {@link ZnightMetadata} object (`__ZNIGHT_METADATA__`). The runtime (container, plugins) only ever
 * consumes this object: there is no reflection and no decorator metadata at runtime.
 *
 * This file is the single source of truth shared by the compiler (which emits code matching these
 * types) and every runtime package. See docs/internals/architecture.md §3. Any field whose absence
 * changes runtime behaviour requires bumping {@link METADATA_VERSION}.
 */

/** Version of the metadata format produced by the compiler and accepted by the runtime. */
export const METADATA_VERSION = 1

/**
 * Unique, stable identifier of a provider: the canonical identity of the declaration that defines it.
 *
 * - application class: `src/users/user.service.ts#UserService`
 * - package export: `@acme/auth#JwtService`, `@znight/observability#Logger`
 * - `@Provides` method: `src/db/db.factory.ts#DbFactory.createPool`
 */
export type Token = string

/**
 * Lifetime of a provider instance.
 * - `singleton`: one instance for the whole application (default)
 * - `request`: one instance per scope (see `Container.runInScope`)
 * - `transient`: a new instance every time it is injected or resolved
 */
export type Scope = 'singleton' | 'request' | 'transient'

/** Lifecycle hooks a singleton may implement (detected at runtime by duck typing). */
export type LifecycleHook = 'onStart' | 'onReady' | 'onStop'

/**
 * A dependency in a provider's `deps` list:
 * - `Token`: required dependency
 * - `{ token, optional: true }`: `undefined` when no provider/value exists
 * - `{ multi: [...] }`: array of instances, in the given order
 * - `{ lazy: token }`: a {@link Lazy} handle resolved at call time in the current scope
 */
export type DependencyRef =
  | Token
  | { readonly token: Token; readonly optional: true }
  | { readonly multi: readonly Token[] }
  | { readonly lazy: Token }

/** Handle injected for `Lazy<T>` parameters: resolves the dependency when `get()` is called. */
export interface Lazy<T> {
  get(): T
}

/**
 * Factory generated by the compiler. Receives resolved dependencies in the same order as
 * {@link ProviderDefinition.deps}.
 */
// biome-ignore lint/suspicious/noExplicitAny: generated factories receive heterogeneously typed dependencies
export type ProviderFactory<T = unknown> = (deps: any[]) => T | Promise<T>

/** Location of a declaration in the user's source code (path relative to the project root, 1-based). */
export interface SourceLocation {
  readonly file: string
  readonly line: number
  readonly column: number
}

/** One interceptor applied to a method: `dep` is an index in {@link ProviderDefinition.deps}. */
export interface InterceptorBinding {
  readonly dep: number
  readonly options?: unknown
}

/** Interceptor chain of a method. The first binding is the outermost interceptor. */
export interface MethodInterception {
  /** Whether the intercepted method is async (`async` keyword or `Promise` return type). */
  readonly async: boolean
  readonly chain: readonly InterceptorBinding[]
}

/** Constructor of a provider class (abstract classes allowed for typing purposes). */
export type ProviderClass<T = unknown> = abstract new (...args: never[]) => T

/** Runtime definition of a single provider. */
export interface ProviderDefinition<T = unknown> {
  readonly scope: Scope
  /** Class reference, when the provider is a class. Enables `container.get(MyClass)`. */
  readonly class?: ProviderClass<T>
  /** Dependencies passed positionally to {@link factory}. */
  readonly deps: readonly DependencyRef[]
  readonly factory: ProviderFactory<T>
  /** `true` when the factory returns a promise. Only allowed for singletons. */
  readonly async?: boolean
  /** Method interceptors (AOP), applied by the container right after {@link factory}. */
  readonly interceptors?: Readonly<Record<string, MethodInterception>>
  /** Name of a method to call on shutdown, for objects without `onStop`/`Symbol.asyncDispose`. */
  readonly dispose?: string
  /** Qualifier set with `@Named()`. */
  readonly name?: string
  /** Set with `@Primary()`. */
  readonly primary?: boolean
  readonly source?: SourceLocation
}

/**
 * A token the compiled code depends on but that is supplied at runtime (by a plugin through
 * `container.registerValue()` / `container.register()`, or by `Application.create({ providers })`).
 */
export interface ExternalDefinition {
  readonly token: Token
  /** Scope of the supplied value. Request-scoped externals are read from the active scope. Default: singleton. */
  readonly scope?: Scope
  /** Name of the plugin expected to provide it (used in error messages). */
  readonly providedBy?: string
  readonly optional?: boolean
}

/**
 * Feature-specific metadata (HTTP routes, message consumers, config classes...).
 * Packages augment this interface with their own key:
 *
 * ```ts
 * declare module '@znight/core' {
 *   interface ZnightExtensionsMetadata { http?: HttpMetadata }
 * }
 * ```
 */
export interface ZnightExtensionsMetadata {
  readonly [extension: string]: unknown
}

/** The complete metadata generated by `@znight/compiler`. */
export interface ZnightMetadata {
  /** Format version of this object, see {@link METADATA_VERSION}. */
  readonly version: number
  /** Version of `@znight/compiler` that generated this object. */
  readonly compiler?: string
  readonly providers: Readonly<Record<Token, ProviderDefinition>>
  /** Every provider token, topologically sorted: dependencies always come before their dependents. */
  readonly resolutionOrder: readonly Token[]
  /** Alternative tokens (provided types, interfaces, base classes) pointing to a provider token. */
  readonly aliases?: Readonly<Record<Token, Token>>
  readonly externals?: readonly ExternalDefinition[]
  readonly extensions?: ZnightExtensionsMetadata
}
