/** Options of {@link Container.init}. */
export interface InitOptions {
  /**
   * Instantiate only these providers and their dependency closure. Other singletons are created on
   * first use (synchronously; async factories must be part of the closure).
   */
  readonly only?: readonly ProviderKey[]
}

/** An instantiated singleton managed by the container (see {@link Container.instances}). */
export interface ManagedInstance {
  readonly token: Token
  readonly displayName: string
  readonly instance: unknown
  readonly definition: ProviderDefinition
  /** Disposes the instance once (dispose method, `Symbol.asyncDispose` or `Symbol.dispose`). */
  dispose(): Promise<void>
}

/** Seed values of a request scope: token-keyed pairs (aliases and known classes are accepted). */
export type ScopeValues = Iterable<readonly [ProviderKey, unknown]>

type Status = 'open' | 'initializing' | 'ready' | 'failed' | 'disposed'

interface InitRun {
  failed: boolean
  readonly errors: unknown[]
  readonly inflight: Promise<void>[]
}

interface ContainerInternals {
  bindBuiltin(container: Container, token: Token, value: unknown, cls?: object): void
  setOrigin(container: Container, origin: string | undefined): void
}

