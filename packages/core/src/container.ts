/**
 * The dependency injection container. It consumes the metadata generated by `@znight/compiler`:
 * no reflection happens at runtime, factories are called in a precomputed order and resolving a
 * singleton is a single `Map` lookup.
 *
 * ```ts
 * const container = Container.create(__ZNIGHT_METADATA__)
 * container.registerValue('@acme/clock#Clock', systemClock)
 * await container.init()
 * const users = container.get(UserService)
 * ```
 *
 * Precedence of bindings: `override()` > plugin `register()`/`registerValue()` >
 * `Application.create({ providers })` (`provide()`) > compiled providers. Registrations are only
 * possible before `init()` (ZNIGHT016).
 */
export class Container {
  /** The metadata this container was created from. */
  readonly metadata: ZnightMetadata
  /** Canonical slots, in insertion order (compiled providers first). */
  readonly #slots = new Map<Token, Slot>()
  /** Every lookup key (tokens, aliases, classes, cached display names) → slot. */
  readonly #lookup = new Map<unknown, Slot>()
  /** Alias token → canonical slot (used to index alias display names). */
  readonly #aliases = new Map<Token, Slot>()
  readonly #storage = new AsyncLocalStorage<RequestScope>()
  /** Instantiated singletons, in creation order. */
  readonly #created: Slot[] = []
  #order: readonly Slot[] = []
  #names: Map<string, Slot[]> | undefined
  #status: Status = 'open'
  #sealed = false
  #planned = false
  // biome-ignore lint/style/useReadonlyClassProperties: assigned through the internals accessor (static block)
  #origin: string | undefined
  #initPromise: Promise<void> | undefined
  #disposePromise: Promise<void> | undefined

  static {
    internals = {
      bindBuiltin: (container, token, value, cls) => container.#bindBuiltin(token, value, cls),
      setOrigin: (container, origin) => {
        container.#origin = origin
      },
    }
  }

  private constructor(metadata: ZnightMetadata) {
    this.metadata = metadata
    for (const [token, definition] of Object.entries(metadata.providers)) {
      validateDefinition(token, definition)
      const slot = this.#slot(token)
      slot.compiled = true
      slot.compiledSource = definition.source
      this.#applyDefinition(slot, definition, LEVEL_COMPILED, 'the compiled metadata')
    }
    if (metadata.aliases !== undefined) this.#indexAliases(metadata.aliases)
    for (const external of metadata.externals ?? []) this.#declareExternal(external)
    this.#bindBuiltin(CoreTokens.Container, this, Container)
  }

  /**
   * Creates a container from compiled metadata.
   *
   * @throws ZnightError (ZNIGHT018) when the metadata format version is not supported.
   */
  static create(metadata: ZnightMetadata): Container {
    if (
      metadata === null ||
      typeof metadata !== 'object' ||
      metadata.providers === null ||
      typeof metadata.providers !== 'object' ||
      !Array.isArray(metadata.resolutionOrder)
    ) {
      throw invalidMetadataError()
    }
    if (metadata.version !== METADATA_VERSION) throw metadataVersionError(metadata, METADATA_VERSION)
    return new Container(metadata)
  }

  // ---------------------------------------------------------------------------------------------
  // Registration
  // ---------------------------------------------------------------------------------------------

  /**
   * Registers a runtime provider definition (plugin precedence). It may depend on compiled tokens.
   *
   * @throws ZnightError ZNIGHT016 after `init()`, ZNIGHT004 when the token is a compiled provider or
   *   is already registered, ZNIGHT005/ZNIGHT014 for an invalid definition.
   */
  register<T>(token: TypedToken<T>, definition: ProviderDefinition<NoInfer<T>>): void {
    this.#assertOpen('register', token)
    validateDefinition(token, definition)
    this.#bind(token, LEVEL_PLUGIN, 'register', (slot, origin) =>
      this.#applyDefinition(slot, definition, LEVEL_PLUGIN, origin),
    )
  }

  /**
   * Registers a value (plugin precedence), typically for an external declared in the metadata.
   * Ignored when the token is overridden.
   *
   * @throws ZnightError ZNIGHT016 after `init()`, ZNIGHT004 when the token is a compiled provider or
   *   is already registered.
   */
  registerValue<T>(token: TypedToken<T>, value: NoInfer<T>): void {
    this.#bind(token, LEVEL_PLUGIN, 'register a value for', (slot, origin) =>
      this.#applyValue(slot, value, LEVEL_PLUGIN, origin),
    )
  }

  /**
   * Declares an external token supplied at runtime (like `metadata.externals`). A request-scoped
   * external is read from the active scope (`runInScope` seed values).
   */
  registerExternal(external: ExternalDefinition): void {
    this.#assertOpen('declare the external', external.token)
    this.#declareExternal(external)
  }

  /**
   * Supplies a value with application precedence (`Application.create({ providers })`): replaces a
   * compiled provider, is superseded by plugin registrations and overrides.
   */
  provide<T>(key: ProviderKey<T>, value: NoInfer<T>): void {
    this.#bind(key, LEVEL_APPLICATION, 'provide', (slot, origin) =>
      this.#applyValue(slot, value, LEVEL_APPLICATION, origin),
    )
  }

  /**
   * Replaces a provider (highest precedence, typically in tests). `key` may be a token, an alias or
   * a class (aliases are resolved first). `valueOrDefinition` is used as a provider definition when
   * it has the shape of one (`{ scope, deps, factory }`), as a value otherwise.
   */
  override<T>(key: ProviderKey<T>, valueOrDefinition: NoInfer<T> | ProviderDefinition<NoInfer<T>>): void {
    this.#bind(key, LEVEL_OVERRIDE, 'override', (slot, origin) => {
      if (isProviderDefinition(valueOrDefinition)) {
        validateDefinition(slot.token, valueOrDefinition)
        this.#applyDefinition(slot, valueOrDefinition, LEVEL_OVERRIDE, origin)
      } else {
        this.#applyValue(slot, valueOrDefinition, LEVEL_OVERRIDE, origin)
      }
    })
  }

  // ---------------------------------------------------------------------------------------------
  // Initialisation
  // ---------------------------------------------------------------------------------------------

  /**
   * Seals the container, validates the merged graph (missing providers ZNIGHT001, cycles ZNIGHT002,
   * scope mismatches ZNIGHT003) and instantiates singletons. A factory starts as soon as its
   * dependencies are ready, so independent async singletons are created concurrently. On failure,
   * created instances are disposed in reverse creation order and the first error is rethrown
   * (ZNIGHT015 for factory errors, with other failures attached, see `getSuppressedErrors`).
   *
   * Calling `init()` again returns the promise of the first call.
   */
  init(options: InitOptions = {}): Promise<void> {
    if (this.#initPromise !== undefined) return this.#initPromise
    if (this.#disposePromise !== undefined) {
      return Promise.reject(
        new ZnightError(ErrorCode.InstantiationFailed, 'Cannot initialise a container that has been disposed'),
      )
    }
    this.#sealed = true
    this.#status = 'initializing'
    this.#initPromise = this.#initialize(options)
    return this.#initPromise
  }

  async #initialize(options: InitOptions): Promise<void> {
    try {
      const roots = options.only?.map(key => this.#rootSlot(key))
      const lookup = (token: Token): Slot => this.#lookup.get(token) ?? this.#slot(token)
      for (const slot of [...this.#slots.values()]) if (slot.isProvider) buildPlan(slot, lookup)
      const order = computeOrder(this.#baseOrder())
      analyseScopes(order)
      this.#order = order
      this.#planned = true

      const closure = roots === undefined ? undefined : closureOf(roots)
      const missing = findMissing(closure ?? order)
      for (const root of roots ?? []) if (isMissing(root) && !missing.has(root)) missing.set(root, [])
      if (missing.size > 0) throw missingProvidersError(missing)

      const singletons = order.filter(slot => slot.mode === SINGLETON && (closure === undefined || closure.has(slot)))
      await this.#instantiate(singletons)
      this.#status = 'ready'
    } catch (error) {
      this.#status = 'failed'
      throw error
    }
  }

  *#baseOrder(): Iterable<Slot> {
    for (const token of this.metadata.resolutionOrder) {
      const slot = this.#slots.get(token)
      if (slot !== undefined) yield slot
    }
    yield* this.#slots.values()
  }

  async #instantiate(singletons: readonly Slot[]): Promise<void> {
    const run: InitRun = { failed: false, errors: [], inflight: [] }
    for (const slot of singletons) {
      if (run.failed) break
      if (slot.state === IDLE) this.#schedule(slot, run)
    }
    await Promise.all(run.inflight)
    if (!run.failed) return
    const cleanup = await this.#rollback()
    const [first, ...others] = run.errors
    addSuppressedErrors(first, [...others, ...cleanup])
    throw first
  }

  /** Starts `slot` now, or as soon as the singletons it waits for are ready. */
  #schedule(slot: Slot, run: InitRun): void {
    const waits: Promise<void>[] = []
    for (const dep of slot.waits) {
      // not reachable with a topological order: schedule the dependency first rather than fail obscurely
      if (dep.state === IDLE) this.#schedule(dep, run)
      const state: number = dep.state
      if (state === READY) continue
      if (state !== PENDING || dep.promise === undefined) return // a dependency failed: the run is failing
      waits.push(dep.promise)
    }
    if (waits.length === 0) {
      const promise = this.#start(slot, run)
      if (promise !== undefined) run.inflight.push(promise)
      return
    }
    slot.state = PENDING
    const promise = Promise.all(waits).then(() => {
      slot.state = IDLE
      return run.failed ? undefined : this.#start(slot, run)
    })
    slot.promise = promise
    run.inflight.push(promise)
  }

  /** Calls the factory of a singleton during `init()`. Never throws: failures are recorded in `run`. */
  #start(slot: Slot, run: InitRun): Promise<void> | undefined {
    const definition = slot.definition as ProviderDefinition
    slot.state = CREATING
    let deps: unknown[]
    let result: unknown
    try {
      deps = this.#resolveDeps(slot)
    } catch (error) {
      this.#fail(slot, this.#initError(slot, error, false), run)
      return undefined
    }
    try {
      result = definition.factory(deps)
    } catch (error) {
      this.#fail(slot, this.#initError(slot, error, true), run)
      return undefined
    }
    if (!isThenable(result)) {
      this.#complete(slot, result, deps, run)
      return undefined
    }
    slot.state = PENDING
    const promise = Promise.resolve(result).then(
      instance => this.#complete(slot, instance, deps, run),
      (error: unknown) => this.#fail(slot, this.#initError(slot, error, true), run),
    )
    slot.promise = promise
    return promise
  }

  #complete(slot: Slot, instance: unknown, deps: readonly unknown[], run: InitRun): void {
    slot.instance = instance
    slot.state = READY
    slot.promise = undefined
    this.#created.push(slot)
    const interceptors = slot.definition?.interceptors
    if (interceptors === undefined) return
    try {
      applyInterceptors(instance as object, interceptors, deps, slot.displayName)
    } catch (error) {
      // the instance exists: it stays registered as created so the rollback disposes it
      run.failed = true
      run.errors.push(this.#initError(slot, error, true))
    }
  }

  #fail(slot: Slot, error: unknown, run: InitRun): void {
    slot.state = FAILED
    slot.promise = undefined
    run.failed = true
    run.errors.push(error)
  }

  #initError(slot: Slot, error: unknown, fromFactory: boolean): unknown {
    const path = dependentPath(slot, this.#order)
    if (fromFactory) return new InstantiationError(slot.token, path, error, slot.definition?.source)
    if (error instanceof InstantiationError) return error.withParents(path)
    return error
  }

  async #rollback(): Promise<unknown[]> {
    const errors: unknown[] = []
    for (let index = this.#created.length - 1; index >= 0; index--) {
      const slot = this.#created[index] as Slot
      try {
        const result = this.#disposeSlot(slot)
        if (result !== undefined) await result
      } catch (error) {
        errors.push(lifecycleError(`Disposing ${slot.displayName}`, error))
      }
    }
    return errors
  }

  // ---------------------------------------------------------------------------------------------
  // Resolution
  // ---------------------------------------------------------------------------------------------

  /**
   * Resolves a provider by class, token, alias or unique display name (`'UserService'`).
   *
   * @throws ZnightError ZNIGHT001 (no provider), ZNIGHT008 (ambiguous display name), ZNIGHT013
   *   (request-scoped provider outside of a scope), ZNIGHT015 (factory failure or container not
   *   initialised).
   */
  get<T>(key: ProviderClass<T>): T
  get<T>(key: ClassKey<T>): T
  get<T = unknown>(key: TypedToken<T>): T
  get(key: ProviderKey): unknown {
    const slot = this.#lookup.get(key)
    if (slot !== undefined && slot.state === READY) return slot.instance
    return this.#resolveKey(key, slot, false)
  }

  /** Like {@link get}, but returns `undefined` when no provider exists for `key`. */
  getOptional<T>(key: ProviderClass<T>): T | undefined
  getOptional<T>(key: ClassKey<T>): T | undefined
  getOptional<T = unknown>(key: TypedToken<T>): T | undefined
  getOptional(key: ProviderKey): unknown {
    const slot = this.#lookup.get(key)
    if (slot !== undefined && slot.state === READY) return slot.instance
    return this.#resolveKey(key, slot, true)
  }

  /**
   * Whether `key` can be resolved: a provider or value is bound to it, or the active scope holds a
   * value for it. An ambiguous display name returns `false`.
   */
  has(key: ProviderKey): boolean {
    const slot = this.#lookup.get(key) ?? this.#findByName(key, false)
    const scope = this.#storage.getStore()
    if (slot === undefined) return typeof key === 'string' && (scope?.values.has(key) ?? false)
    if (slot.mode !== UNBOUND) return true
    return scope?.values.has(slot.token) ?? false
  }

  /** Canonical token of a class (or alias / display name), `undefined` when unknown. */
  tokenOf(key: ProviderKey): Token | undefined {
    return (this.#lookup.get(key) ?? this.#findByName(key, false))?.token
  }

  /** Instantiated singletons (created by the container, not registered values), in resolution order. */
  instances(): ManagedInstance[] {
    const result: ManagedInstance[] = []
    for (const slot of this.#order) {
      if (slot.mode === SINGLETON && slot.state === READY) result.push(this.#managed(slot))
    }
    return result
  }

  #managed(slot: Slot): ManagedInstance {
    return {
      token: slot.token,
      displayName: slot.displayName,
      instance: slot.instance,
      definition: slot.definition as ProviderDefinition,
      dispose: async (): Promise<void> => {
        await this.#disposeSlot(slot)
      },
    }
  }

  #resolveKey(key: ProviderKey, found: Slot | undefined, optional: boolean): unknown {
    const slot = found ?? this.#findByName(key, true)
    if (slot !== undefined) return this.#resolve(slot, optional)
    if (typeof key === 'string') {
      const scope = this.#storage.getStore()
      if (scope?.values.has(key)) return scope.values.get(key)
    }
    if (optional) return undefined
    throw notFoundError(key)
  }

  #resolve(slot: Slot, optional: boolean): unknown {
    switch (slot.mode) {
      case VALUE:
        return slot.instance
      case SINGLETON:
        return slot.state === READY ? slot.instance : this.#createOnDemand(slot)
      case REQUEST:
        return this.#resolveRequest(slot)
      case TRANSIENT:
        this.#assertResolvable(slot)
        return this.#create(slot)
      default:
        return this.#resolveUnbound(slot, optional)
    }
  }

  #resolveDeps(slot: Slot): unknown[] {
    const plan = slot.plan as readonly DepPlan[]
    const deps = new Array<unknown>(plan.length)
    for (let index = 0; index < plan.length; index++) deps[index] = this.#resolveDep(plan[index] as DepPlan)
    return deps
  }

  #resolveDep(dep: DepPlan): unknown {
    switch (dep.kind) {
      case DEP_REQUIRED:
        return this.#resolve(dep.slot as Slot, false)
      case DEP_OPTIONAL:
        return this.#resolve(dep.slot as Slot, true)
      case DEP_MULTI:
        return (dep.slots as readonly Slot[]).map(target => this.#resolve(target, false))
      case DEP_LAZY:
        return this.#lazy(dep.slot as Slot)
      default:
        return undefined
    }
  }

  #lazy(slot: Slot): Lazy<unknown> {
    return { get: () => this.#resolve(slot, false) }
  }

  /** Instantiates a request-scoped or transient provider (synchronous factories only). */
  #create(slot: Slot): unknown {
    const definition = slot.definition as ProviderDefinition
    let deps: unknown[]
    try {
      deps = this.#resolveDeps(slot)
    } catch (error) {
      throw error instanceof InstantiationError ? error.withParents([slot.token]) : error
    }
    let instance: unknown
    try {
      instance = definition.factory(deps)
    } catch (error) {
      throw new InstantiationError(slot.token, [slot.token], error, definition.source)
    }
    if (definition.interceptors !== undefined) {
      try {
        applyInterceptors(instance as object, definition.interceptors, deps, slot.displayName)
      } catch (error) {
        throw new InstantiationError(slot.token, [slot.token], error, definition.source)
      }
    }
    return instance
  }

  #resolveRequest(slot: Slot): unknown {
    const scope = this.#storage.getStore()
    if (scope === undefined) throw noScopeError(slot)
    if (scope.closed) throw closedScopeError(slot)
    const values = scope.values
    const existing = values.get(slot.token)
    if (existing !== undefined || values.has(slot.token)) return existing
    this.#assertResolvable(slot)
    const instance = this.#create(slot)
    values.set(slot.token, instance)
    scope.created.push({ token: slot.token, instance, dispose: slot.definition?.dispose })
    return instance
  }

  #resolveUnbound(slot: Slot, optional: boolean): unknown {
    const scope = this.#storage.getStore()
    if (scope?.values.has(slot.token)) return scope.values.get(slot.token)
    const external = slot.external
    if (external?.scope === 'request') {
      if (scope === undefined) throw noScopeError(slot)
      if (optional || external.optional === true) return undefined
      throw missingScopeValueError(slot)
    }
    if (optional || external?.optional === true) return undefined
    throw notFoundError(slot.token, slot)
  }

  /**
   * Creates a singleton synchronously outside of the `init()` schedule (lazy access, `init({ only })`).
   * Like during `init()`, the factory runs outside of any request scope: a singleton belongs to the
   * application, so the timers, sockets and promises it creates must not capture the scope of the
   * request that happens to use it first.
   */
  #createOnDemand(slot: Slot): unknown {
    if (this.#storage.getStore() !== undefined) return this.#storage.exit(() => this.#createOnDemand(slot))
    switch (slot.state) {
      case CREATING:
        throw reentrantCreationError(slot)
      case PENDING:
        throw notReadyError(slot)
      case FAILED:
        throw failedProviderError(slot)
      case DISPOSED:
        throw unavailableError(slot, 'disposed')
      default:
        break
    }
    this.#assertResolvable(slot)
    for (const dep of slot.waits) if (dep.state !== READY) this.#createOnDemand(dep)
    const definition = slot.definition as ProviderDefinition
    if (definition.async === true) throw asyncOnDemandError(slot, true)
    slot.state = CREATING
    let deps: unknown[]
    let result: unknown
    try {
      deps = this.#resolveDeps(slot)
    } catch (error) {
      slot.state = IDLE
      throw error instanceof InstantiationError ? error.withParents([slot.token]) : error
    }
    try {
      result = definition.factory(deps)
    } catch (error) {
      slot.state = IDLE
      throw new InstantiationError(slot.token, [slot.token], error, definition.source)
    }
    if (isThenable(result)) {
      slot.state = IDLE
      // undeclared async factory: release whatever it produces, the caller gets an error
      Promise.resolve(result).then(
        instance => disposeQuietly(instance, definition.dispose),
        () => undefined,
      )
      throw asyncOnDemandError(slot, false)
    }
    if (definition.interceptors !== undefined) {
      try {
        applyInterceptors(result as object, definition.interceptors, deps, slot.displayName)
      } catch (error) {
        slot.state = IDLE
        disposeQuietly(result, definition.dispose)
        throw new InstantiationError(slot.token, [slot.token], error, definition.source)
      }
    }
    slot.instance = result
    slot.state = READY
    this.#created.push(slot)
    return result
  }

  #assertResolvable(slot: Slot): void {
    const status = this.#status
    if (status === 'ready' || (status === 'initializing' && this.#planned)) return
    throw unavailableError(slot, status === 'disposed' || status === 'failed' ? status : 'open')
  }

  // ---------------------------------------------------------------------------------------------
  // Request scope
  // ---------------------------------------------------------------------------------------------

  /**
   * Runs `fn` in a new request scope seeded with `values`. Request-scoped providers and
   * request-scoped externals resolved inside `fn` (including asynchronously) are bound to this
   * scope. When `fn` settles, the instances created in the scope are disposed in reverse creation
   * order. Scopes are isolated from each other (nested calls open a fresh scope).
   *
   * Rejects with the error of `fn` (disposal errors attached), or with ZNIGHT021 when only the
   * disposal failed.
   */
  async runInScope<R>(fn: () => R | Promise<R>, values?: ScopeValues): Promise<R> {
    const scope = new RequestScope(this.#canonical)
    if (values !== undefined) for (const [key, value] of values) scope.values.set(this.#canonical(key), value)
    let result: R
    try {
      result = await this.#storage.run(scope, fn)
    } catch (error) {
      addSuppressedErrors(error, await this.#closeScope(scope))
      throw error
    }
    if (scope.created.length === 0) {
      scope.closed = true
      return result
    }
    const errors = await this.#closeScope(scope)
    if (errors.length > 0) {
      throw new ZnightAggregateError(
        ErrorCode.LifecycleFailed,
        `Failed to dispose ${errors.length} request-scoped instance(s)`,
        errors,
      )
    }
    return result
  }

  /** The active request scope, if any. */
  currentScope(): ScopeContext | undefined {
    return this.#storage.getStore()
  }

  async #closeScope(scope: RequestScope): Promise<unknown[]> {
    scope.closed = true
    const errors: unknown[] = []
    for (let index = scope.created.length - 1; index >= 0; index--) {
      const created = scope.created[index] as ScopedInstance
      try {
        const result = disposeInstance(created.instance, created.dispose)
        if (isThenable(result)) await result
      } catch (error) {
        errors.push(lifecycleError(`Disposing the request-scoped ${displayName(created.token)}`, error))
      }
    }
    return errors
  }

  readonly #canonical = (key: ProviderKey): Token => {
    const slot = this.#lookup.get(key) ?? this.#findByName(key, false)
    if (slot !== undefined) return slot.token
    if (typeof key === 'string') return key
    throw notFoundError(key)
  }

  // ---------------------------------------------------------------------------------------------
  // Disposal
  // ---------------------------------------------------------------------------------------------

  /**
   * Disposes every instantiated singleton in reverse resolution order (dispose method from the
   * definition, `Symbol.asyncDispose` or `Symbol.dispose`). Lifecycle `onStop` hooks are run by the
   * Application, not here. Idempotent; waits for an in-progress `init()`. Registered values are
   * owned by whoever registered them and are not disposed.
   *
   * @throws ZnightAggregateError (ZNIGHT021) listing every disposal failure.
   */
  dispose(): Promise<void> {
    this.#disposePromise ??= this.#disposeAll()
    return this.#disposePromise
  }

  async #disposeAll(): Promise<void> {
    this.#sealed = true
    if (this.#initPromise !== undefined) {
      try {
        await this.#initPromise
      } catch {
        // a failed init already rolled back what it created
      }
    }
    const errors: unknown[] = []
    for (let index = this.#order.length - 1; index >= 0; index--) {
      const slot = this.#order[index] as Slot
      try {
        const result = this.#disposeSlot(slot)
        if (result !== undefined) await result
      } catch (error) {
        errors.push(lifecycleError(`Disposing ${slot.displayName}`, error))
      }
    }
    for (const slot of this.#slots.values()) if (slot.mode === SINGLETON && slot.state === IDLE) slot.state = DISPOSED
    this.#status = 'disposed'
    if (errors.length > 0) {
      throw new ZnightAggregateError(
        ErrorCode.LifecycleFailed,
        `Failed to dispose ${errors.length} provider(s)`,
        errors,
      )
    }
  }

  #disposeSlot(slot: Slot): Promise<unknown> | undefined {
    if (slot.mode !== SINGLETON || slot.state !== READY) return undefined
    slot.state = DISPOSED
    const instance = slot.instance
    slot.instance = undefined
    const result = disposeInstance(instance, slot.definition?.dispose)
    return isThenable(result) ? Promise.resolve(result) : undefined
  }

  // ---------------------------------------------------------------------------------------------
  // Bindings
  // ---------------------------------------------------------------------------------------------

  #slot(token: Token): Slot {
    let slot = this.#slots.get(token)
    if (slot === undefined) {
      slot = new Slot(token)
      this.#slots.set(token, slot)
      if (!this.#lookup.has(token)) this.#lookup.set(token, slot)
    }
    return slot
  }

  #indexAliases(aliases: Readonly<Record<Token, Token>>): void {
    const targets = new Map<Token, Token>(Object.entries(aliases))
    for (const [alias, target] of targets) {
      let canonical = target
      const seen = new Set<Token>([alias])
      while (!this.#slots.has(canonical) && targets.has(canonical) && !seen.has(canonical)) {
        seen.add(canonical)
        canonical = targets.get(canonical) as Token
      }
      const slot = this.#lookup.get(canonical) ?? this.#slot(canonical)
      this.#aliases.set(alias, slot)
      if (!this.#lookup.has(alias)) this.#lookup.set(alias, slot)
    }
  }

  #declareExternal(external: ExternalDefinition): void {
    if (typeof external?.token !== 'string') {
      throw new ZnightError(ErrorCode.InvalidDecorator, `Invalid external definition: ${errorMessage(external)}`)
    }
    const slot = this.#lookup.get(external.token) ?? this.#slot(external.token)
    slot.external = external
    this.#names = undefined
  }

  #bindBuiltin(token: Token, value: unknown, cls?: object): void {
    this.#bind(token, LEVEL_BUILTIN, 'register', (slot, origin) => this.#applyValue(slot, value, LEVEL_BUILTIN, origin))
    if (cls === undefined) return
    const slot = this.#slot(token)
    slot.cls ??= cls
    if (!this.#lookup.has(cls)) this.#lookup.set(cls, slot)
  }

  #assertOpen(action: string, key: unknown): void {
    if (this.#sealed) throw sealedError(action, key)
  }

  #bind(key: ProviderKey, level: number, action: string, apply: (slot: Slot, origin: string) => void): void {
    this.#assertOpen(action, key)
    const slot = this.#registrationSlot(key, action)
    if (slot.level > level) return
    if (slot.level === level && level !== LEVEL_OVERRIDE && level !== LEVEL_BUILTIN) {
      throw duplicateRegistrationError(action, slot)
    }
    if (level === LEVEL_PLUGIN && slot.compiled) throw compiledProviderError(action, slot)
    apply(slot, this.#originOf(level))
  }

  #originOf(level: number): string {
    switch (level) {
      case LEVEL_BUILTIN:
        return '@znight/core'
      case LEVEL_APPLICATION:
        return 'Application.create({ providers })'
      case LEVEL_PLUGIN:
        return this.#origin ?? 'container.register()'
      case LEVEL_OVERRIDE:
        return 'an override'
      default:
        return 'the compiled metadata'
    }
  }

  #registrationSlot(key: ProviderKey, action: string): Slot {
    const slot = this.#lookup.get(key)
    if (slot !== undefined) return slot
    if (typeof key === 'string') return this.#slot(key)
    const byName = this.#findByName(key, true)
    if (byName !== undefined) return byName
    throw unknownClassError(action, key)
  }

  #applyDefinition(slot: Slot, definition: ProviderDefinition, level: number, origin: string): void {
    slot.mode = modeOf(definition)
    slot.definition = definition
    slot.instance = undefined
    slot.state = IDLE
    slot.level = level
    slot.origin = origin
    if (definition.class !== undefined) {
      slot.cls ??= definition.class
      if (!this.#lookup.has(definition.class)) this.#lookup.set(definition.class, slot)
    }
    this.#names = undefined
  }

  #applyValue(slot: Slot, value: unknown, level: number, origin: string): void {
    slot.mode = VALUE
    slot.definition = undefined
    slot.instance = value
    slot.state = READY
    slot.level = level
    slot.origin = origin
    this.#names = undefined
  }

  #rootSlot(key: ProviderKey): Slot {
    const slot = this.#lookup.get(key) ?? this.#findByName(key, true)
    if (slot === undefined) throw notFoundError(key)
    return slot
  }

  /**
   * Display-name (or class-name) lookup. A class key only keeps the candidates of its hierarchy (see
   * `classMatch`): those known to be of that class win over those whose class is unknown. Ambiguity
   * throws ZNIGHT008 when `strict`.
   */
  #findByName(key: unknown, strict: boolean): Slot | undefined {
    let name: string
    if (typeof key === 'string') name = key
    else if (typeof key === 'function' && typeof key.name === 'string' && key.name !== '') name = key.name
    else return undefined
    const candidates = this.#nameIndex().get(name)
    if (candidates === undefined) return undefined
    const matches = typeof key === 'function' ? classCandidates(candidates, key) : candidates
    if (matches.length === 1) {
      const slot = matches[0] as Slot
      if (this.#sealed) this.#lookup.set(key, slot)
      return slot
    }
    if (matches.length === 0 || !strict) return undefined
    throw ambiguousNameError(name, matches)
  }

  #nameIndex(): Map<string, Slot[]> {
    if (this.#names !== undefined) return this.#names
    const index = new Map<string, Slot[]>()
    const add = (name: string, slot: Slot): void => {
      const list = index.get(name)
      if (list === undefined) index.set(name, [slot])
      else if (!list.includes(slot)) list.push(slot)
    }
    for (const slot of this.#slots.values()) {
      if (slot.mode !== UNBOUND || slot.external !== undefined) add(slot.displayName, slot)
    }
    for (const [alias, slot] of this.#aliases) add(displayName(alias), slot)
    this.#names = index
    return index
  }
}

/** Binds `value` under `token` with built-in precedence (internal, used by Application). */
