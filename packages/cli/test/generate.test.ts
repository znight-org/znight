const OUT_FILE = 'src/.znight/container.generated.ts'
const CODE = '// AUTO-GENERATED by @znight/compiler 0.1.0. Do not edit.\nexport const __ZNIGHT_METADATA__ = {}\n'

function diagnostic(severity: 'error' | 'warning', message: string): Diagnostic {
  return {
    code: severity === 'error' ? 'ZNIGHT001' : 'ZNIGHT019',
    severity,
    message,
    location: { file: '/app/src/a.ts', line: 3, column: 5, endLine: 3, endColumn: 9, start: 20, end: 24 },
    hints: ['add @Injectable()'],
  } as Diagnostic
}

/** A compiler writing `code` to the outFile like `generate()` does. */
class FakeCompiler implements CompilerApi {
  readonly calls: {
    method: 'check' | 'generate' | 'incremental'
    options?: ZnightOptions
    changes?: CompilerChanges
  }[] = []
  readonly formatted: FormatDiagnosticsOptions[] = []
  diagnostics: Diagnostic[] = []
  code = CODE
  watchFiles: string[] | undefined
  /** `loadConfig` result (`znight.config.*`); `undefined`: a compiler without `loadZnightConfig()`. */
  config: ((root: string) => Promise<ZnightConfigLike>) | undefined
  readonly configRoots: string[] = []

  get loadConfig(): ((root: string) => Promise<ZnightConfigLike>) | undefined {
    const config = this.config
    if (config === undefined) return undefined
    return root => {
      this.configRoots.push(root)
      return config(root)
    }
  }

  #result(options: ZnightOptions): CompileResultLike {
    return {
      code: this.code,
      outFile: resolve(options.root ?? '.', options.outFile ?? OUT_FILE),
      diagnostics: this.diagnostics,
      stats: { files: 5, providers: 3, durationMs: 12 },
      watchFiles: this.watchFiles,
    }
  }

  #write(options: ZnightOptions): GenerateResultLike {
    const result = this.#result(options)
    return { ...result, written: !hasErrors(result.diagnostics) && writeIfChanged(result.outFile, result.code) }
  }

  generate(options: ZnightOptions): Promise<GenerateResultLike> {
    this.calls.push({ method: 'generate', options })
    return Promise.resolve(this.#write(options))
  }

  check(options: ZnightOptions): Promise<CheckResultLike> {
    this.calls.push({ method: 'check', options })
    const result = this.#result(options)
    const current = existsSync(result.outFile) ? readFileSync(result.outFile, 'utf8') : undefined
    return Promise.resolve({ ...result, stale: current !== result.code })
  }

  createIncremental(options: ZnightOptions): IncrementalCompiler {
    return {
      generate: changes => {
        this.calls.push({ method: 'incremental', ...(changes === undefined ? {} : { changes }) })
        return Promise.resolve(this.#write(options))
      },
      isOutFile: file => resolve(file) === resolve(options.root ?? '.', OUT_FILE),
    }
  }

  formatDiagnostics(diagnostics: readonly Diagnostic[], options: FormatDiagnosticsOptions = {}): string {
    this.formatted.push(options)
    return diagnostics.map(item => `[formatted] ${item.code} ${item.message}`).join('\n')
  }
}

describe('znight generate', () => {
  let project: { path: string; cleanup: () => void }
  let compiler: FakeCompiler

  beforeEach(() => {
    project = temporaryDirectory()
    writeFileSync(join(project.path, 'package.json'), '{"name":"app"}')
    compiler = new FakeCompiler()
  })

  afterEach(() => project.cleanup())

  function generate(argv: readonly string[] = [], extra: Parameters<typeof runCli>[1] = {}) {
    return runCli(['generate', ...argv], {
      cwd: project.path,
      ...extra,
      services: {
        loadCompiler: root => {
          expect(root).toBe(project.path)
          return Promise.resolve(compiler)
        },
        ...extra.services,
      },
    })
  }

  it('writes the generated module and reports it', async () => {
    const run = await generate()
    expect(run.code).toBe(0)
    expect(run.stdout).toBe('✓ Generated src/.znight/container.generated.ts (3 providers, 5 files, 12ms)\n')
    expect(readFileSync(join(project.path, OUT_FILE), 'utf8')).toBe(CODE)
    expect(compiler.calls).toEqual([{ method: 'generate', options: { root: project.path } }])

    const again = await generate()
    expect(again.stdout).toContain('✓ Up to date: src/.znight/container.generated.ts')
  })

  it('prints the diagnostics with formatDiagnostics and fails on errors', async () => {
    compiler.diagnostics = [diagnostic('error', 'Missing provider'), diagnostic('warning', 'Unused provider')]
    const run = await generate()
    expect(run.code).toBe(1)
    expect(run.stderr).toContain('[formatted] ZNIGHT001 Missing provider')
    expect(run.stderr).toContain('[formatted] ZNIGHT019 Unused provider')
    expect(run.stderr).toContain('✗ Generation failed with 1 error')
    expect(compiler.formatted).toEqual([{ color: false, cwd: project.path, summary: false }])
    expect(existsSync(join(project.path, OUT_FILE))).toBe(false)
  })

  it('succeeds with warnings only', async () => {
    compiler.diagnostics = [diagnostic('warning', 'Unused provider')]
    const run = await generate(['--color'])
    expect(run.code).toBe(0)
    expect(run.stderr).toContain('[formatted] ZNIGHT019 Unused provider')
    expect(compiler.formatted).toEqual([{ color: true, cwd: project.path, summary: false }])
  })

  describe('--check', () => {
    it('fails when the file is missing', async () => {
      const run = await generate(['--check'])
      expect(run.code).toBe(1)
      expect(run.stderr).toContain('src/.znight/container.generated.ts is missing')
      expect(compiler.calls.map(call => call.method)).toEqual(['check'])
      expect(existsSync(join(project.path, OUT_FILE))).toBe(false)
    })

    it('fails when the file is out of date', async () => {
      mkdirSync(join(project.path, 'src/.znight'), { recursive: true })
      writeFileSync(join(project.path, OUT_FILE), '// old')
      const run = await generate(['--check'])
      expect(run.code).toBe(1)
      expect(run.stderr).toContain('src/.znight/container.generated.ts is out of date')
      expect(readFileSync(join(project.path, OUT_FILE), 'utf8')).toBe('// old')
    })

    it('succeeds when the file is up to date', async () => {
      await generate()
      const run = await generate(['--check'])
      expect(run.code).toBe(0)
      expect(run.stdout).toContain('✓ src/.znight/container.generated.ts is up to date')
    })

    it('fails on compilation errors', async () => {
      await generate()
      compiler.diagnostics = [diagnostic('error', 'Missing provider')]
      const run = await generate(['--check'])
      expect(run.code).toBe(1)
      expect(run.stderr).toContain('Generation failed with 1 error')
    })
  })

  describe('options', () => {
    it('honours --root', async () => {
      const app = join(project.path, 'apps/api')
      mkdirSync(app, { recursive: true })
      const run = await runCli(['generate', '--root', 'apps/api'], {
        cwd: project.path,
        services: { loadCompiler: () => Promise.resolve(compiler) },
      })
      expect(run.code).toBe(0)
      expect(compiler.calls[0]?.options?.root).toBe(app)
      expect(run.stdout).toContain('apps/api/src/.znight/container.generated.ts')
    })

    it('does not load Vite without a Vite config', async () => {
      let loaded = false
      const run = await generate([], {
        services: {
          loadVite: () => {
            loaded = true
            return Promise.reject(new Error('unexpected'))
          },
        },
      })
      expect(run.code).toBe(0)
      expect(loaded).toBe(false)
    })

    it('reads the options of the znight() plugin from vite.config.ts', async () => {
      writeFileSync(join(project.path, 'vite.config.ts'), 'export default {}')
      const plugin = { name: 'znight', api: { options: { outFile: 'src/generated/container.ts', reportUnused: true } } }
      const vite = new FakeVite({ configPlugins: [[{ name: 'other' }], Promise.resolve(plugin)] })
      const run = await generate([], { services: { loadVite: () => Promise.resolve(vite) } })
      expect(run.code).toBe(0)
      expect(vite.loadedConfigs).toBe(1)
      expect(compiler.calls[0]?.options).toEqual({
        outFile: 'src/generated/container.ts',
        reportUnused: true,
        root: project.path,
      })
      expect(run.stdout).toContain('Generated src/generated/container.ts')
    })

    it('uses the defaults when the plugin does not expose its options', async () => {
      writeFileSync(join(project.path, 'vite.config.ts'), 'export default {}')
      const vite = new FakeVite({ configPlugins: [{ name: 'znight' }] })
      const run = await generate([], { services: { loadVite: () => Promise.resolve(vite) } })
      expect(run.code).toBe(0)
      expect(run.stderr).toBe('')
      expect(compiler.calls[0]?.options).toEqual({ root: project.path })
    })

    it('warns when the Vite config does not use znight()', async () => {
      writeFileSync(join(project.path, 'vite.config.ts'), 'export default {}')
      const vite = new FakeVite({ configPlugins: [] })
      const run = await generate([], { services: { loadVite: () => Promise.resolve(vite) } })
      expect(run.code).toBe(0)
      expect(run.stderr).toContain('vite.config.ts does not register the znight() plugin')
    })

    it('reads znight.config.* first, without loading Vite', async () => {
      writeFileSync(join(project.path, 'vite.config.ts'), 'export default {}')
      compiler.config = root =>
        Promise.resolve({
          file: join(root, 'znight.config.ts'),
          options: { root, outFile: 'src/di/container.ts', reportUnused: true, logLevel: 'info' },
        })
      let viteLoaded = false
      const run = await generate([], {
        services: {
          loadVite: () => {
            viteLoaded = true
            return Promise.reject(new Error('unexpected'))
          },
        },
      })
      expect(run.code).toBe(0)
      expect(viteLoaded).toBe(false)
      expect(compiler.configRoots).toEqual([project.path])
      // logLevel is an option of the Bun preload: not passed to the compiler
      expect(compiler.calls[0]?.options).toEqual({
        root: project.path,
        outFile: 'src/di/container.ts',
        reportUnused: true,
      })
      expect(run.stdout).toContain('Generated src/di/container.ts')
    })

    it('resolves the root of znight.config.* against the project root', async () => {
      compiler.config = () =>
        Promise.resolve({ file: join(project.path, 'znight.config.ts'), options: { root: 'app' } })
      const run = await generate()
      expect(run.code).toBe(0)
      expect(compiler.calls[0]?.options).toEqual({ root: join(project.path, 'app') })
    })

    it('falls back to the Vite config without znight.config.*', async () => {
      compiler.config = root => Promise.resolve({ file: undefined, options: { root } })
      writeFileSync(join(project.path, 'vite.config.ts'), 'export default {}')
      const vite = new FakeVite({ configPlugins: [{ name: 'znight', api: { options: { prune: true } } }] })
      const run = await generate([], { services: { loadVite: () => Promise.resolve(vite) } })
      expect(run.code).toBe(0)
      expect(vite.loadedConfigs).toBe(1)
      expect(compiler.calls[0]?.options).toEqual({ prune: true, root: project.path })
    })

    it('reads the Vite config given with --config instead of znight.config.*', async () => {
      compiler.config = root => Promise.resolve({ file: join(root, 'znight.config.ts'), options: { root } })
      writeFileSync(join(project.path, 'vite.custom.ts'), 'export default {}')
      const vite = new FakeVite({ configPlugins: [{ name: 'znight', api: { options: { prune: true } } }] })
      const run = await generate(['--config', 'vite.custom.ts'], {
        services: { loadVite: () => Promise.resolve(vite) },
      })
      expect(run.code).toBe(0)
      expect(compiler.configRoots).toEqual([])
      expect(compiler.calls[0]?.options).toEqual({ prune: true, root: project.path })
    })

    it('fails when znight.config.* cannot be loaded', async () => {
      compiler.config = () => Promise.reject(new Error('[znight] ZNIGHT_CONFIG points to a missing file: /x.ts'))
      const run = await generate()
      expect(run.code).toBe(1)
      expect(run.stderr).toContain('Cannot load the Znight config (znight.config.*)')
      expect(run.stderr).toContain('ZNIGHT_CONFIG points to a missing file')
      expect(compiler.calls).toEqual([])
    })

    it('falls back to the defaults when the Vite config cannot be loaded, fails with --config', async () => {
      writeFileSync(join(project.path, 'vite.config.ts'), 'export default {}')
      const broken = { loadVite: () => Promise.reject(new Error('Cannot find package "vite"')) }
      const run = await generate([], { services: broken })
      expect(run.code).toBe(0)
      expect(run.stderr).toContain('Cannot read the znight() options from the Vite config, using the defaults')

      const explicit = await generate(['--config', 'vite.config.ts'], { services: broken })
      expect(explicit.code).toBe(1)
      expect(explicit.stderr).toContain('Cannot load the Vite config vite.config.ts')
    })
  })

  it('regenerates incrementally on changes with --watch', async () => {
    const signals = new FakeSignals()
    let onChange: ((file: string) => void) | undefined
    let targets: readonly WatchTarget[] = []
    let closed = false
    const src = join(project.path, 'src')
    mkdirSync(src)
    writeFileSync(join(src, 'known.ts'), '')
    writeFileSync(join(src, 'new.ts'), '')
    compiler.watchFiles = [join(src, 'known.ts'), join(src, 'gone.ts')]
    const running = generate(['--watch'], {
      signals,
      services: {
        watch: (watched, listener) => {
          targets = watched
          onChange = listener
          return {
            close: () => {
              closed = true
            },
          }
        },
      },
    })
    await waitFor(() => onChange !== undefined)
    expect(targets).toEqual([
      { path: join(project.path, 'src'), recursive: true },
      { path: project.path, recursive: false },
    ])
    expect(compiler.calls).toEqual([{ method: 'incremental' }])

    // a burst of changes: one compile with the classified files
    onChange?.(join(src, 'known.ts'))
    onChange?.(join(src, 'new.ts'))
    onChange?.(join(src, 'gone.ts'))
    onChange?.(join(src, 'known.ts'))
    await waitFor(() => compiler.calls.length === 2)
    expect(compiler.calls[1]).toEqual({
      method: 'incremental',
      changes: { changed: [join(src, 'known.ts')], added: [join(src, 'new.ts')], removed: [join(src, 'gone.ts')] },
    })
    // writing the generated file does not trigger a new generation
    onChange?.(join(project.path, OUT_FILE))
    await new Promise(resolve => setTimeout(resolve, 80))
    expect(compiler.calls).toHaveLength(2)

    // errors are printed and the watch goes on
    compiler.diagnostics = [diagnostic('error', 'Missing provider')]
    onChange?.(join(src, 'known.ts'))
    await waitFor(() => compiler.calls.length === 3)

    signals.emit('SIGINT')
    const run = await running
    expect(run.code).toBe(0)
    expect(closed).toBe(true)
    expect(run.stdout).toContain('Watching for changes...')
    expect(run.stdout).toContain('✓ Generated src/.znight/container.generated.ts')
    expect(run.stderr).toContain('[formatted] ZNIGHT001 Missing provider')
  })
})

describe('compiler adapter', () => {
  let directory: { path: string; cleanup: () => void }
  let outFile: string

  beforeEach(() => {
    directory = temporaryDirectory()
    outFile = join(directory.path, OUT_FILE)
  })

  afterEach(() => directory.cleanup())

  const result = (code = 'x', diagnostics: Diagnostic[] = []) => ({ code, outFile, diagnostics })

  it('uses generate(), generate({ check }) and createCompiler() of the compiler', async () => {
    const seen: unknown[] = []
    const api = adaptCompilerModule({
      generate: options => {
        seen.push(options)
        if (options?.check === true) return Promise.resolve({ ...result(), stale: true })
        return Promise.resolve({ ...result(), written: [outFile] })
      },
      createCompiler: options => ({
        generate: changes => {
          seen.push({ incremental: options, changes })
          return Promise.resolve({ ...result(), written: [] })
        },
        isOutFile: file => file === 'generated',
      }),
    })
    expect((await api.generate({ root: directory.path })).written).toBe(true)
    expect((await api.check({ root: directory.path })).stale).toBe(true)
    const incremental = api.createIncremental({ root: directory.path })
    expect((await incremental.generate({ changed: ['a.ts'] })).written).toBe(false)
    expect(incremental.isOutFile('generated')).toBe(true)
    expect(seen).toEqual([
      { root: directory.path },
      { root: directory.path, check: true },
      { incremental: { root: directory.path }, changes: { changed: ['a.ts'] } },
    ])
  })

  it('exposes loadZnightConfig() as loadConfig', async () => {
    const roots: (string | undefined)[] = []
    const api = adaptCompilerModule({
      generate: () => Promise.resolve(result()),
      loadZnightConfig: cwd => {
        roots.push(cwd)
        return Promise.resolve({ file: undefined, options: { root: cwd } })
      },
    })
    expect(await api.loadConfig?.(directory.path)).toEqual({ file: undefined, options: { root: directory.path } })
    expect(roots).toEqual([directory.path])
    expect(adaptCompilerModule({ generate: () => Promise.resolve(result()) }).loadConfig).toBeUndefined()
  })

  it('detects writes and staleness when the compiler does not report them', async () => {
    const api = adaptCompilerModule({
      generate: options => {
        if (options?.check !== true) writeIfChanged(outFile, 'x')
        return Promise.resolve(result())
      },
    })
    expect((await api.check({ root: directory.path })).stale).toBe(true)
    expect((await api.generate({ root: directory.path })).written).toBe(true)
    expect((await api.generate({ root: directory.path })).written).toBe(false)
    expect((await api.check({ root: directory.path })).stale).toBe(false)
  })

  it('builds everything on compile() when generate() is missing', async () => {
    let code = 'v1'
    const api = adaptCompilerModule({ compile: () => Promise.resolve(result(code)) })
    expect((await api.check({ root: directory.path })).stale).toBe(true)
    expect((await api.generate({ root: directory.path })).written).toBe(true)
    expect(readFileSync(outFile, 'utf8')).toBe('v1')
    expect((await api.check({ root: directory.path })).stale).toBe(false)
    const incremental = api.createIncremental({ root: directory.path })
    expect((await incremental.generate()).written).toBe(false)
    code = 'v2'
    expect((await incremental.generate({ changed: ['a.ts'] })).written).toBe(true)
    expect(incremental.isOutFile(outFile)).toBe(true)
    expect(incremental.isOutFile(join(directory.path, 'src/a.ts'))).toBe(false)
  })

  it('never writes when there are errors', async () => {
    const api = adaptCompilerModule({
      compile: () => Promise.resolve(result('throw', [diagnostic('error', 'Missing')])),
    })
    expect((await api.generate({ root: directory.path })).written).toBe(false)
    expect(existsSync(outFile)).toBe(false)
  })

  it('formats diagnostics with the compiler, or with a built-in formatter', () => {
    const custom = adaptCompilerModule({ compile: () => Promise.resolve(result()), formatDiagnostics: () => 'custom' })
    expect(custom.formatDiagnostics([diagnostic('error', 'Missing')])).toBe('custom')
    const builtin = adaptCompilerModule({ compile: () => Promise.resolve(result()) })
    expect(builtin.formatDiagnostics([diagnostic('error', 'Missing')], {})).toContain('✗ ZNIGHT001: Missing')
  })

  it('rejects a compiler without compile() and generate()', () => {
    expect(() => adaptCompilerModule({})).toThrow('exposes neither compile() nor generate()')
  })

  it('loads @znight/compiler from the project', async () => {
    const directory = temporaryDirectory()
    try {
      const root = directory.path
      const pkg = join(root, 'node_modules/@znight/compiler')
      mkdirSync(pkg, { recursive: true })
      writeFileSync(
        join(pkg, 'package.json'),
        JSON.stringify({ name: '@znight/compiler', type: 'module', main: 'index.js' }),
      )
      writeFileSync(
        join(pkg, 'index.js'),
        "export const compile = async () => ({ code: 'from-project', outFile: '/x', diagnostics: [] })\n",
      )
      writeFileSync(join(root, 'package.json'), '{"name":"app"}')
      const api = await loadCompiler(root)
      expect((await api.check({})).code).toBe('from-project')
    } finally {
      directory.cleanup()
    }
  })

  it('formats diagnostics without the compiler formatter', () => {
    const text = fallbackFormatDiagnostics(
      [
        diagnostic('error', "Missing provider for 'EmailService' required by NotificationService"),
        {
          ...diagnostic('warning', 'Unused provider'),
          related: [{ message: 'declared here', location: diagnostic('warning', '').location }],
        } as Diagnostic,
      ],
      { cwd: '/app' },
    )
    expect(text).toMatchSnapshot()
  })
})
