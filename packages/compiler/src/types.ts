/**
 * Provider scope types
 */
export type ProviderScope = 'singleton' | 'request' | 'transient';

/**
 * Lifecycle hook names
 */
export type LifecycleHook = 'onStart' | 'onStop' | 'onReady';

/**
 * Metadata for a single provider
 */
export interface ProviderMetadata {
  /** Class name */
  name: string;

  /** Import path for the class */
  importPath: string;

  /** Provider scope */
  scope: ProviderScope;

  /** List of dependency names (constructor parameters) */
  dependencies: string[];

  /** Lifecycle hooks implemented by this provider */
  lifecycle: LifecycleHook[];

  /** Whether this provider is marked as @Primary */
  isPrimary?: boolean;
}

/**
 * HTTP method types
 */
export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH' | 'HEAD' | 'OPTIONS';

/**
 * Parameter source for HTTP handlers
 */
export type ParamSource = 'param' | 'query' | 'body' | 'header' | 'request' | 'response';

/**
 * Metadata for a route parameter
 */
export interface ParamMetadata {
  /** Parameter index in the method signature */
  index: number;

  /** Parameter source (param, query, body, etc.) */
  source: ParamSource;

  /** Parameter name (for @Param('id'), @Query('page'), etc.) */
  name?: string;
}

/**
 * Metadata for a single route
 */
export interface RouteMetadata {
  /** HTTP method */
  method: HttpMethod;

  /** Route path */
  path: string;

  /** Handler method name */
  handlerName: string;

  /** Parameters metadata */
  params: ParamMetadata[];

  /** Guards to apply */
  guards?: string[];

  /** Interceptors to apply */
  interceptors?: string[];
}

/**
 * Metadata for a controller
 */
export interface ControllerMetadata {
  /** Controller class name */
  name: string;

  /** Import path for the controller */
  importPath: string;

  /** Base path for all routes in this controller */
  basePath: string;

  /** Routes defined in this controller */
  routes: RouteMetadata[];

  /** Dependencies (injected services) */
  dependencies: string[];
}

/**
 * Metadata for a message consumer
 */
export interface ConsumerMetadata {
  /** Consumer class name */
  name: string;

  /** Import path for the consumer */
  importPath: string;

  /** Queue or topic name */
  queue: string;

  /** Handler method name */
  handlerName: string;

  /** Retry configuration */
  retry?: {
    attempts: number;
    backoff: 'fixed' | 'exponential';
    delay?: number;
  };

  /** Dependencies (injected services) */
  dependencies: string[];
}

/**
 * Complete application metadata generated by the compiler
 */
export interface ApplicationMetadata {
  /** All providers in the application */
  providers: Record<string, ProviderMetadata>;

  /** All controllers in the application */
  controllers: Record<string, ControllerMetadata>;

  /** All consumers in the application */
  consumers: Record<string, ConsumerMetadata>;

  /** Topologically sorted resolution order for providers */
  resolutionOrder: string[];
}
