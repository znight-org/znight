import type { ApplicationMetadata, ProviderMetadata } from '../types.js';
import { topologicalSort } from './topological-sort.js';

/**
 * Generates the container code from application metadata
 */
export class ContainerGenerator {
  /**
   * Generates the complete container.generated.ts file content
   */
  generate(providers: Map<string, ProviderMetadata>): string {
    const lines: string[] = [];

    // Add file header
    lines.push('/**');
    lines.push(' * AUTO-GENERATED FILE - DO NOT EDIT');
    lines.push(' * Generated by @znight/compiler');
    lines.push(` * Generated at: ${new Date().toISOString()}`);
    lines.push(' */');
    lines.push('');

    // Generate imports
    lines.push(...this.generateImports(providers));
    lines.push('');

    // Generate metadata object
    lines.push(...this.generateMetadata(providers));

    return lines.join('\n');
  }

  /**
   * Generates import statements for all providers
   */
  private generateImports(providers: Map<string, ProviderMetadata>): string[] {
    const lines: string[] = [];
    const imports = new Map<string, string[]>();

    // Group providers by import path
    for (const provider of providers.values()) {
      const existing = imports.get(provider.importPath) || [];
      existing.push(provider.name);
      imports.set(provider.importPath, existing);
    }

    // Generate import statements
    for (const [path, names] of imports.entries()) {
      const namesStr = names.join(', ');
      lines.push(`import { ${namesStr} } from '${path}.js';`);
    }

    return lines;
  }

  /**
   * Generates the metadata object
   */
  private generateMetadata(providers: Map<string, ProviderMetadata>): string[] {
    const lines: string[] = [];

    // Calculate resolution order
    const resolutionOrder = topologicalSort(providers);

    // Start metadata object
    lines.push('export const __ZNIGHT_METADATA__ = {');
    lines.push('  providers: {');

    // Generate each provider entry
    const providerEntries: string[] = [];
    for (const [name, provider] of providers.entries()) {
      providerEntries.push(this.generateProviderEntry(name, provider));
    }
    lines.push(providerEntries.join(',\n'));

    lines.push('  },');
    lines.push('');

    // Add resolution order
    lines.push('  resolutionOrder: [');
    for (const name of resolutionOrder) {
      lines.push(`    '${name}',`);
    }
    lines.push('  ],');
    lines.push('');

    // Add controllers and consumers (empty for now)
    lines.push('  controllers: {},');
    lines.push('  consumers: {},');

    lines.push('};');

    return lines;
  }

  /**
   * Generates a single provider entry
   */
  private generateProviderEntry(
    name: string,
    provider: ProviderMetadata,
  ): string {
    const lines: string[] = [];

    lines.push(`    '${name}': {`);
    lines.push(`      class: ${provider.name},`);
    lines.push(`      scope: '${provider.scope}',`);

    // Dependencies array
    const deps = provider.dependencies.map((d) => `'${d}'`).join(', ');
    lines.push(`      dependencies: [${deps}],`);

    // Lifecycle hooks array
    const hooks = provider.lifecycle.map((h) => `'${h}'`).join(', ');
    lines.push(`      lifecycle: [${hooks}],`);

    // Factory function
    if (provider.dependencies.length === 0) {
      lines.push(`      factory: () => new ${provider.name}(),`);
    } else {
      lines.push('      factory: (deps) => {');
      const depArgs = provider.dependencies.join(', ');
      const destructured = provider.dependencies
        .map((d) => `deps['${d}']`)
        .join(', ');
      lines.push(`        return new ${provider.name}(${destructured});`);
      lines.push('      },');
    }

    // Primary flag
    if (provider.isPrimary) {
      lines.push('      isPrimary: true,');
    }

    lines.push('    }');

    return lines.join('\n');
  }
}
