/**
 * Merges compiled provider libraries (§6.4) into the application before binding: the
 * `znight.providers.json` fragments referenced by `package.json#znight.providers` of the root
 * dependencies. Their providers become regular provider drafts (bound with §4.7 against the whole
 * application: library dependencies are validated against the application providers), their
 * extension data is appended to the extension's stored data and their `bindInjection` requests are
 * bound again.
 *
 * The provider classes are found through the package's declarations (`dist/*.d.mts`), which also
 * give the import routes, heritage and lifecycle methods; the fragment provides what declarations
 * lose (decorators: qualifiers, scopes, interceptors, injection points).
 */
import type { Scope, Token } from '@znight/core'
import type { Reporter } from '../analysis/arguments.ts'
import type { ClassAnalyzer } from '../analysis/class-analyzer.ts'
import type { ProviderRegistry } from '../analysis/registry.ts'
import type { ClassInfo, LifecycleHookName } from '../extensions/api.ts'
import type { AnalysisState } from '../extensions/contexts.ts'
import type { Location, PackageInfo, Project, ReferenceType, TypeInfo } from '../project/index.ts'
import type { EncodedValue, LibraryInjection, LibraryProvider, ProvidersFile } from './schema.ts'

import fs from 'node:fs'
import { ErrorCode } from '@znight/core'

import { LIFECYCLE_MEMBERS } from '../analysis/core-decorators.ts'
import { createBindingHandle } from '../extensions/contexts.ts'
import { compareStrings } from '../project/compare.ts'
import { displayNameOf, relativePath, serializeType, ValueRef } from '../project/index.ts'
import { decodeValue, PROVIDERS_SCHEMA_VERSION } from './schema.ts'

/** Inputs of {@link mergeCompiledLibraries}. */
export interface MergeInput {
  readonly project: Project
  readonly analyzer: ClassAnalyzer
  readonly registry: ProviderRegistry
  readonly state: AnalysisState
  /** Names of the loaded extensions (data of other extensions is reported and ignored). */
  readonly extensions: ReadonlySet<string>
  readonly report: Reporter
}

/** A compiled library found in the dependencies of the root package. */
export interface CompiledLibrary {
  readonly package: PackageInfo
  /** Absolute path of its `znight.providers.json`. */
  readonly file: string
}

const SCOPES: readonly string[] = ['singleton', 'request', 'transient']

/** Root dependencies declaring `"znight": { "providers": ... }` (source libraries excluded), sorted. */
export function compiledLibraries(project: Project): CompiledLibrary[] {
  const root = project.rootPackage
  if (!root) {
    return []
  }
  const sources = new Set(project.libraries().map(library => library.package.dir))
  const found: CompiledLibrary[] = []
  for (const name of [...project.packages.dependencyNames(root)].sort(compareStrings)) {
    const info = project.packages.findInstalled(name, project.root)
    if (!info || info.dir === root.dir || sources.has(info.dir)) {
      continue
    }
    const file = project.manifestOf(info)?.providers
    if (file !== undefined) {
      found.push({ package: info, file })
    }
  }
  return found
}

/** Merges every compiled library of the application. */
export function mergeCompiledLibraries(input: MergeInput): void {
  for (const library of compiledLibraries(input.project)) {
    mergeLibrary(input, library)
  }
}

function mergeLibrary(input: MergeInput, library: CompiledLibrary): void {
  const { report } = input
  const name = library.package.publicName ?? library.package.name ?? library.package.dir
  const where = `${name}/${relativePath(library.package.dir, library.file)}`
  const problem = (message: string, hints: readonly string[] = []): void => {
    report({
      code: ErrorCode.VersionMismatch,
      severity: 'error',
      message: `Compiled provider library ${name} (${where}): ${message}`,
      ...(hints.length > 0 ? { hints } : {}),
    })
  }
  let data: ProvidersFile
  try {
    data = JSON.parse(fs.readFileSync(library.file, 'utf8')) as ProvidersFile
  } catch (error) {
    problem(`cannot be read (${error instanceof Error ? error.message : String(error)})`, [
      `Build ${name} (its znight.providers.json is generated by the compiler in library mode)`,
    ])
    return
  }
  if (typeof data !== 'object' || data === null || data.schemaVersion !== PROVIDERS_SCHEMA_VERSION) {
    problem(
      `unsupported schemaVersion ${JSON.stringify((data as { schemaVersion?: unknown } | null)?.schemaVersion)} (expected ${PROVIDERS_SCHEMA_VERSION})`,
      [`Use versions of ${name} and @znight/compiler of the same release line`],
    )
    return
  }
  if (!Array.isArray(data.providers) || !Array.isArray(data.edges) || !Array.isArray(data.bindings)) {
    problem('malformed file (providers, edges and bindings must be arrays)')
    return
  }
  const fileLocation: Location = { file: library.file, line: 1, column: 1, endLine: 1, endColumn: 1, start: 0, end: 0 }

  // Bindings are re-created with new handle ids before the extension data that references them.
  const handles = new Map<number, object>()
  for (const binding of data.bindings) {
    const id = input.state.nextBindingId++
    handles.set(binding.id, createBindingHandle(id))
    const request = decodeInjection(binding, input)
    input.state.bindings.push({
      id,
      from: binding.from,
      site: {
        owner: binding.from === undefined ? name : displayNameOf(binding.from),
        label: binding.label,
        subject: capitalize(binding.label),
        location: fileLocation,
        spec: request,
        rest: false,
      },
    })
  }

  for (const provider of [...data.providers].sort((a, b) => compareStrings(a.token, b.token))) {
    const cls = input.analyzer.infoOfIdentity(provider.class)
    if (!cls) {
      problem(`the declaration of ${provider.class} cannot be found`, [
        `Check that ${name} is built with its declarations (types) and exports ${displayNameOf(provider.class)}`,
      ])
      continue
    }
    if (input.registry.has(provider.token)) {
      report({
        code: ErrorCode.DuplicateProvider,
        severity: 'warning',
        message: `${displayNameOf(provider.token)} is provided by the compiled library ${name} and registered again by the application: the application wins`,
        location: input.registry.get(provider.token)?.registration ?? cls.location,
      })
      continue
    }
    if (!SCOPES.includes(provider.scope)) {
      problem(`invalid scope ${JSON.stringify(provider.scope)} for ${provider.token}`)
      continue
    }
    input.registry.add(draftOf(input, provider, cls, name))
  }

  for (const edge of data.edges) {
    input.state.edges.push({ from: edge.from, to: edge.to, location: fileLocation, reason: edge.reason })
  }

  for (const extension of Object.keys(data.extensions ?? {}).sort(compareStrings)) {
    const stored = data.extensions[extension] ?? []
    if (!input.extensions.has(extension)) {
      report({
        code: ErrorCode.VersionMismatch,
        severity: 'warning',
        message: `Compiled provider library ${name} contains data of the compiler extension '${extension}', which is not loaded: it is ignored`,
        hints: [`Install the package providing the '${extension}' extension and import it in the application`],
      })
      continue
    }
    let list = input.state.stored.get(extension)
    if (!list) {
      list = []
      input.state.stored.set(extension, list)
    }
    for (const value of stored) {
      list.push(decode(value, input, handles, library, fileLocation))
    }
  }
}

function draftOf(
  input: MergeInput,
  provider: LibraryProvider,
  cls: ClassInfo,
  library: string,
): Parameters<ProviderRegistry['add']>[0] {
  const providedType = decodeType(provider.providedType, input)
  const heritage = (decodeType(provider.heritage, input) as unknown as readonly ReferenceType[]) ?? []
  const lifecycle = provider.lifecycle.flatMap(member => {
    const hook: LifecycleHookName | undefined = LIFECYCLE_MEMBERS.get(member)
    return hook
      ? [{ hook, member, declaredBy: provider.class, static: false, requiredParams: 0, location: cls.location }]
      : []
  })
  const params = provider.params.map(param => {
    const spec = decodeInjection(param, input)
    return { spec, label: param.label, subject: capitalize(param.label), location: cls.location, rest: false }
  })
  const interceptors = provider.interceptors.map(method => ({
    method: { name: method.method, async: method.async },
    chain: method.chain.map(link => ({
      token: link.token,
      hasOptions: link.options !== undefined,
      options:
        link.options === undefined
          ? undefined
          : (decode(link.options, input, new Map(), undefined, cls.location) as never),
      decorator: { identity: link.decorator, name: displayNameOf(link.decorator), location: cls.location },
    })),
  }))
  return {
    token: provider.token,
    displayName: displayNameOf(provider.token),
    kind: provider.kind,
    registeredBy: provider.registeredBy,
    cls,
    method: provider.method === undefined ? undefined : { name: provider.method },
    providedType,
    exactKey: serializeType(providedType),
    heritage,
    scope: provider.scope as Scope,
    name: provider.name,
    primary: provider.primary === true,
    async: provider.async === true,
    dispose: provider.dispose,
    location: cls.location,
    registration: cls.location,
    registeredWith: `compiled provider library ${library}`,
    params,
    custom: undefined,
    interceptors,
    lifecycle,
    factoryToken: provider.kind === 'provides' ? (provider.class as Token) : undefined,
    skipBinding: false,
  }
}

function decodeInjection(
  injection: LibraryInjection,
  input: MergeInput,
): { readonly type: TypeInfo; readonly qualifier: string | undefined; readonly optional: boolean } {
  return {
    type: decodeType(injection.type, input),
    qualifier: injection.qualifier,
    optional: injection.optional === true,
  }
}

function decodeType(value: EncodedValue, input: MergeInput): TypeInfo {
  return decode(value, input, new Map(), undefined, undefined) as TypeInfo
}

function decode(
  value: EncodedValue,
  input: MergeInput,
  handles: ReadonlyMap<number, object>,
  library: CompiledLibrary | undefined,
  location: Location | undefined,
): unknown {
  return decodeValue(value, {
    ref: identity => {
      const symbol = input.project.lookupIdentity(identity)
      const fallback: Location = location ?? {
        file: library?.file ?? input.project.root,
        line: 1,
        column: 1,
        endLine: 1,
        endColumn: 1,
        start: 0,
        end: 0,
      }
      return new ValueRef(identity, displayNameOf(identity), displayNameOf(identity), symbol, fallback)
    },
    classInfo: identity => input.analyzer.infoOfIdentity(identity),
    binding: id => handles.get(id),
    location: encoded => ({
      file: library ? `${library.package.dir}/${String(encoded.file)}` : String(encoded.file),
      line: Number(encoded.line),
      column: Number(encoded.column),
      endLine: Number(encoded.endLine),
      endColumn: Number(encoded.endColumn),
      start: Number(encoded.start),
      end: Number(encoded.end),
    }),
  })
}

function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1)
}
